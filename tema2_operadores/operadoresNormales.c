#include <stdio.h>

int main() {
    // Operadores aritmeticos
    printf("%d\n", 1 + 1); //2
    printf("%d\n", 1 - 1); //2
    printf("%d\n", 10 * 2); //2
    printf("%d\n", 10 / 2); //2

    //Operadores comparativos
    printf("%d\n", 4 == 4); //1
    printf("%d\n", 4 == '4'); //0
    printf("%d\n", 4 != 5); //1
    printf("%d\n", 4 < 5);
    printf("%d\n", 4 >= 5); //0

    return 0;

}